document.querySelector('#save-checkin').addEventListener('click', async () => {
  const status = document.querySelector('#checkin-status');
  if (!selectedMood) { status.textContent = t('chooseMood'); return; }
  try {
    const response = await fetch('/api/checkins', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ mood: selectedMood, note: document.querySelector('#checkin-note').value }) });
    if (!response.ok) throw new Error();
    status.textContent = t('checkinSaved');
    document.querySelector('#checkin-note').value = '';
  } catch { status.textContent = t('saveFailed'); }
});
document.querySelector('#reminder-form').addEventListener('submit', (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const data = new FormData(form);
  const reminders = loadList(storageKeys.reminders);
  reminders.push({ id: crypto.randomUUID(), name: data.get('name').trim(), time: data.get('time') });
  saveList(storageKeys.reminders, reminders);
  renderReminders(); form.reset(); document.querySelector('#reminder-dialog').close();
});
