const storageKeys = { reminders: 'thunai.reminders', contacts: 'thunai.contacts', notes: 'thunai.notes' };
let language = localStorage.getItem('thunai.language') || 'en';
let selectedMood = '';
const chatHistory = [];

function t(key) { return translations[language][key] || translations.en[key] || key; }
function loadList(key) {
  try { const value = JSON.parse(localStorage.getItem(key) || '[]'); return Array.isArray(value) ? value : []; }
  catch { return []; }
}
function saveList(key, value) { localStorage.setItem(key, JSON.stringify(value)); }
function escapeHTML(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character]);
}
function applyLanguage() {
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((element) => { element.textContent = t(element.dataset.i18n); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-language]').forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle('is-selected', active);
    button.setAttribute('aria-pressed', String(active));
  });
  renderReminders();
  renderNotes();
  renderContacts();
}
function renderDate() {
  const date = new Date();
  const locale = language === 'ta' ? 'ta-IN' : 'en-US';
  document.querySelector('#current-date').textContent = new Intl.DateTimeFormat(locale, { weekday: 'long', month: 'long', day: 'numeric' }).format(date);
}
function showView(name) {
  document.querySelectorAll('.view').forEach((section) => {
    const active = section.id === `view-${name}`;
    section.classList.toggle('is-visible', active);
    section.hidden = !active;
  });
  document.querySelectorAll('.nav-link').forEach((button) => {
    const active = button.dataset.view === name;
    button.classList.toggle('is-active', active);
    if (active) button.setAttribute('aria-current', 'page'); else button.removeAttribute('aria-current');
  });
  document.querySelector('#main').focus({ preventScroll: true });
  window.scrollTo({ top: 0, behavior: 'smooth' });
}
function renderReminders() {
  const reminders = loadList(storageKeys.reminders).sort((a, b) => a.time.localeCompare(b.time));
  const render = (items) => items.length ? items.map((item) => `<div class="reminder-row"><span class="reminder-time">${escapeHTML(item.time)}</span><span class="reminder-name">${escapeHTML(item.name)}</span><button class="reminder-delete" type="button" data-delete-reminder="${escapeHTML(item.id)}">${escapeHTML(t('delete'))}</button></div>`).join('') : `<p class="empty-state">${escapeHTML(t('noReminders'))}</p>`;
  document.querySelector('#today-reminders').innerHTML = render(reminders.slice(0, 3));
  document.querySelector('#all-reminders').innerHTML = render(reminders);
}
function renderNotes() {
  const notes = loadList(storageKeys.notes);
  const target = document.querySelector('#notes-list');
  target.innerHTML = notes.length ? notes.map((note) => `<article class="note-card">${escapeHTML(note.text)}<br><button type="button" data-delete-note="${escapeHTML(note.id)}">${escapeHTML(t('delete'))}</button></article>`).join('') : `<div class="panel list-panel empty-state">${escapeHTML(t('noNotes'))}</div>`;
}
function renderContacts() {
  const contacts = loadList(storageKeys.contacts);
  const target = document.querySelector('#contacts-list');
  target.innerHTML = contacts.length ? contacts.map((contact) => `<article class="contact-card"><span class="contact-avatar" aria-hidden="true">${escapeHTML(contact.name.trim().charAt(0).toUpperCase())}</span><div class="contact-info"><strong>${escapeHTML(contact.name)}</strong><span>${escapeHTML(contact.phone)}</span></div><a class="call-link" href="tel:${escapeHTML(contact.phone.replace(/[^+\d]/g, ''))}">${escapeHTML(t('call'))}</a><button class="reminder-delete" type="button" data-delete-contact="${escapeHTML(contact.id)}">${escapeHTML(t('delete'))}</button></article>`).join('') : `<p class="empty-state">${escapeHTML(t('noContacts'))}</p>`;
}
function openDialog(id) { document.querySelector(`#${id}`).showModal(); }
function addMessage(content, role) {
  const row = document.createElement('div');
  row.className = `chat-message ${role === 'assistant' ? 'assistant-message' : 'user-message'}`;
  if (role === 'assistant') {
    const avatar = document.createElement('span');
    avatar.className = 'message-avatar'; avatar.setAttribute('aria-hidden', 'true'); avatar.textContent = 'த';
    row.append(avatar);
  }
  const bubble = document.createElement('p');
  bubble.textContent = content;
  row.append(bubble);
  document.querySelector('#chat-messages').append(row);
  row.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  return row;
}
async function sendChat(message) {
  const cleanMessage = message.trim();
  if (!cleanMessage) { document.querySelector('#chat-input').focus(); return; }
  addMessage(cleanMessage, 'user');
  const pending = addMessage(t('thinking'), 'assistant');
  const sendButton = document.querySelector('#chat-form button');
  sendButton.disabled = true;
  try {
    const messages = [...chatHistory, { role: 'user', content: cleanMessage }].slice(-10);
    const response = await fetch('/api/chat', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ messages }) });
    const result = await response.json();
    if (!response.ok) throw new Error(result.error || t('chatUnavailable'));
    pending.querySelector('p').textContent = result.reply;
    chatHistory.push({ role: 'user', content: cleanMessage }, { role: 'assistant', content: result.reply });
  } catch (error) {
    pending.querySelector('p').textContent = error.message.includes('not configured') ? t('chatSetup') : error.message;
  } finally {
    sendButton.disabled = false;
  }
}

